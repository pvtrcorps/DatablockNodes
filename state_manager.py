def define_new_state(datablock_type: str, name: str) -> dict:
    """
    Defines a "template" property dictionary for a datablock that is to be created.
    This is the blueprint for new proxies generated by nodes.

    Args:
        datablock_type: The type of datablock (e.g., 'OBJECT', 'MESH').
        name: The name for the new datablock.

    Returns:
        A dictionary with the default properties for that datablock type.
    """
    # Base properties for all types
    base_state = {
        'name': name,
        'datablock_type': datablock_type.upper(),
    }

    # Type-specific templates
    if datablock_type.upper() == 'OBJECT':
        base_state.update({
            'location': [0.0, 0.0, 0.0],
            'rotation_euler': [0.0, 0.0, 0.0],
            'scale': [1.0, 1.0, 1.0],
        })
    
    elif datablock_type.upper() == 'SCENE':
        base_state.update({
            'render.resolution_x': 1920,
            'render.resolution_y': 1080,
            'render.engine': 'CYCLES',
            'cycles.samples': 128,
        })

    elif datablock_type.upper() == 'LIGHT':
        base_state.update({
            'type': 'POINT',
            'energy': 100.0,
            'color': [1.0, 1.0, 1.0]
        })

    # More templates can be added for 'MESH', 'CAMERA', 'MATERIAL', etc.

    return base_state